import StyleDictionary from "style-dictionary";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { format } from "prettier";
import { fileURLToPath, pathToFileURL } from "node:url";
import { resolve } from "node:path";
import { createTokenConfig } from "../style-dictionary.config.js";

// Style Dictionary owns parsing, merging, reference resolution, transforms and CSS formatting.
// This orchestration only combines mode outputs and checks deterministic generated artifacts.
export async function compileTokens() {
  const manifest = {
    themes: {},
    source: JSON.parse(
      await readFile(
        new URL("../tokens/options/colors.light.json", import.meta.url),
        "utf8",
      ),
    ).$extensions["com.even.provenance"],
  };
  const css = [
    "/* Generated by Style Dictionary. Edit tokens/options or tokens/decisions; run npm run tokens:generate. */",
  ];
  const wide = [];
  for (const theme of ["light", "dark"]) {
    manifest.themes[theme] = {};
    for (const gamut of ["srgb", "p3"]) {
      const dictionary = new StyleDictionary(
        createTokenConfig({ theme, gamut }),
      );
      const [{ output }] = await dictionary.formatPlatform("css");
      const { allTokens } = await dictionary.getPlatformTokens("css");
      manifest.themes[theme][gamut] = Object.fromEntries(
        allTokens.map((token) => [
          token.path.join("."),
          {
            value: token.$value,
            name: token.name,
            reference:
              typeof token.original.$value === "string" &&
              token.original.$value.startsWith("{")
                ? token.original.$value.slice(1, -1)
                : null,
            description: token.$description ?? "",
            type: token.$type,
          },
        ]),
      );
      if (gamut === "srgb") {
        css.push(
          `[data-even-theme="${theme}"] { color-scheme: ${theme}; }`,
          output,
        );
      } else wide.push(output);
    }
  }
  css.push(
    `@media (color-gamut: p3) { @supports (color: oklch(0% 0 0)) { ${wide.join("\n")} } }`,
  );
  return {
    "tokens.css": await format(css.join("\n"), { parser: "css" }),
    "token-manifest.json": await format(JSON.stringify(manifest), {
      parser: "json",
    }),
  };
}

export async function buildTokens({ check = false } = {}) {
  const directory = new URL("../src/tokens/generated/", import.meta.url);
  const outputs = await compileTokens();
  if (!check) await mkdir(directory, { recursive: true });
  for (const [name, content] of Object.entries(outputs)) {
    const file = new URL(name, directory);
    if (check) {
      let existing;
      try {
        existing = await readFile(file, "utf8");
      } catch {
        throw new Error(
          `Missing generated ${name}. Run npm run tokens:generate.`,
        );
      }
      if (existing !== content)
        throw new Error(
          `Generated ${name} is stale. Run npm run tokens:generate.`,
        );
    } else await writeFile(file, content);
  }
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  await buildTokens({ check: process.argv.includes("--check") });
}
